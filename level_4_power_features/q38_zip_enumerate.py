# Q38 — Power Features: zip() and enumerate()
# Practice these patterns:
#
# 1. Use zip() to pair these two lists and print each pair:
names  = ["Alice", "Bob", "Carol"]
scores = [85, 92, 78]
# Expected output: "Alice scored 85", "Bob scored 92", etc.

# 2. Use enumerate() to print items with their index (starting from 1, not 0):
tasks = ["Write tests", "Review PR", "Deploy", "Update docs"]
# Expected: "1. Write tests", "2. Review PR", etc.

# 3. Use zip() to create a dict from two lists in one line:
keys   = ["name", "age", "city"]
values = ["Alice", 30, "Mumbai"]
# Expected: {"name": "Alice", "age": 30, "city": "Mumbai"}
